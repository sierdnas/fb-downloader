let currentLang = "en";

function t(key, vars) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  let str = dict[key] !== undefined ? dict[key] : (TRANSLATIONS.en[key] !== undefined ? TRANSLATIONS.en[key] : key);
  if (vars) {
    Object.keys(vars).forEach((k) => {
      str = str.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]);
    });
  }
  return str;
}

function applyTranslations(langCode) {
  currentLang = FULLY_TRANSLATED.includes(langCode) ? langCode : "en";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.getAttribute("data-i18n-html"));
  });

  const notice = document.getElementById("lang-fallback-notice");
  if (notice) {
    notice.style.display = FULLY_TRANSLATED.includes(langCode) ? "none" : "block";
    notice.textContent = t("lang_fallback_notice");
  }
}

function languageLabel(code) {
  const found = LANGUAGES.find((l) => l.code.toLowerCase() === (code || "").toLowerCase());
  return found ? `${found.native} (${found.name})` : code;
}

function resolveLanguageCode(inputText) {
  const text = (inputText || "").trim();
  if (!text) return "en";
  const byCode = LANGUAGES.find((l) => l.code.toLowerCase() === text.toLowerCase());
  if (byCode) return byCode.code;
  const byLabel = LANGUAGES.find(
    (l) =>
      `${l.native} (${l.name})`.toLowerCase() === text.toLowerCase() ||
      l.native.toLowerCase() === text.toLowerCase() ||
      l.name.toLowerCase() === text.toLowerCase()
  );
  if (byLabel) return byLabel.code;
  const partial = LANGUAGES.find(
    (l) => l.native.toLowerCase().startsWith(text.toLowerCase()) || l.name.toLowerCase().startsWith(text.toLowerCase())
  );
  return partial ? partial.code : text.toLowerCase();
}

function populateLanguageOptions() {
  const datalist = document.getElementById("language-options");
  if (!datalist) return;
  datalist.innerHTML = "";
  LANGUAGES.forEach((l) => {
    const opt = document.createElement("option");
    opt.value = `${l.native} (${l.name})`;
    datalist.appendChild(opt);
  });
}
